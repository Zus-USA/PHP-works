<?php

// Массив чисел для обработки
$numbers = [1, 2, 3, 4, 5];

// array_map применение функции ко всем элементам массива
print_r (array_map (fn($n) => $n ** 2, $numbers));

/*
 *     [0] => 1   // 1^2 = 1
 *     [1] => 4   // 2^2 = 4
 *     [2] => 9   // 3^2 = 9
 *     [3] => 16  // 4^2 = 16
 *     [4] => 25  // 5^2 = 25
 */

